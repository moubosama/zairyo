/**
 * 造作材の材積換算層（下地材の拾い量 → 発注材積 m³）
 *
 * プロの拾い出しXLS「造作材集計」シートの数式を踏襲する:
 *   材積(m³) = 断面H(mm) × 断面D(mm) × 長さL(mm) × 本数 × 10⁻⁹
 * ここでは「本数×1本長さ」を合計材長(m)にまとめて受け取る。
 *
 * 【XLS解読メモ（2026-07-15・②木及び建材XLSの数式を直接確認）】
 * - タイプ別シートの「間仕切下地(木)」行は 幅×高さ の積和−開口（=壁面積㎡）で拾われており、
 *   集計表の 84.082「m」は単位表記に反して実態は「壁1枚あたり片面の下地面積(㎡)」。
 *   高さは天井高ではなく下地高 = 現場定数2.57m（標準スラブ間・床仕上げ面〜上階スラブ下端）、
 *   水回りのスラブ下がり(-200)部に立つ壁のみ2.77m（'Ａタイプ'!E123=2.57居室 / H339=2.77便所）。
 *   ※旧解読の「天井高+370mm」説はCH2200の水回りで2.57に偶然一致していただけの誤り（総監査A-2で是正）。
 * - 一方、見積明細（発注の正）の間仕切木軸は 77.3m³/67戸 = 約855m/戸で、
 *   84㎡×断面(0.11m³)の約10倍 → 実際の軸組（両面×縦横@450）の材長に相当する。
 *   この層で「拾い面積 → 実発注材長 → 材積」の換算を行う。
 */

/** 断面規格（見積明細・木材ブロックの表記に対応） */
export const TIMBER_SECTIONS = {
  kiwaneta: { h: 45, d: 30, name: '際根太', spec: 'LVL 30×45' },
  majikiri: { h: 45, d: 30, name: '間仕切木軸', spec: 'LVL 30×45' },
  dobuchi: { h: 45, d: 30, name: '木胴縁（界壁面）', spec: 'LVL 30×45' },
  ceiling: { h: 40, d: 30, name: '天井下地', spec: 'LVL 30×40' },
};

/** 材積(m³) = H(mm)×D(mm)×合計材長(m→mm)×10⁻⁹（XLS造作材集計と同じ丸め=小数4桁） */
export function timberVolumeM3(section, lengthM) {
  if (!section || !(lengthM > 0)) return 0;
  return Math.round(section.h * section.d * (lengthM * 1000) * 1e-9 * 10000) / 10000;
}

/**
 * 間仕切下地(木)の拾い量（壁1枚あたり片面の下地面積㎡。XLS慣行で単位は"m"）→ 実発注材長(m)
 *
 * 幾何的根拠: 木軸間仕切は成30mmの材を壁の面ごとに組む（1本で両面のボードは受けられない）ため、
 *   縦桟（スタッド）@450 両面: 2 × 1/0.45 = 4.44 m/㎡
 *   横桟（胴縁・上下ランナー含む）@450 両面: 2 × 1/0.45 = 4.44 m/㎡
 *   計 8.89 m/㎡
 * 検算: Gタイプ拾い量84.082 × 8.89 × 断面0.00135㎡ = 1.01 m³/戸
 *       ≒ 見積明細 間仕切木軸 77.3m³/67戸 = 1.15 m³/戸（−12%）
 */
export const MAJIKIRI_TIMBER_M_PER_SQM = 2 * (1 / 0.45) + 2 * (1 / 0.45);

export function majikiriTimberLengthM(shitajiSqm) {
  return shitajiSqm > 0 ? shitajiSqm * MAJIKIRI_TIMBER_M_PER_SQM : 0;
}

/**
 * 天井下地の材長(m) = 天井面積(㎡) × (野縁@303格子 + 吊木)
 *
 * 幾何的根拠: 野縁30×40を@303で縦横の格子に組む（2/0.303 = 6.6 m/㎡）+
 *   吊木@910角（1/0.91² ≒ 1.2本/㎡）× 天井ふところ370mm（上記XLS解読メモの下地高と同値）。
 * 検算: G天井59.09㎡ → 417m → 0.50 m³ ≒ 見積明細 天井下地 38.5m³/67戸 = 0.57 m³/戸（−13%）
 * （@303片方向+野縁受け@910だと4.4m/㎡=0.31m³となり実績の半分 → 格子組みが実績と整合）
 */
export const CEILING_FRAME_M_PER_SQM = 2 / 0.303 + (1 / (0.91 * 0.91)) * 0.37;

export function ceilingFrameLengthM(ceilingSqm) {
  return ceilingSqm > 0 ? ceilingSqm * CEILING_FRAME_M_PER_SQM : 0;
}

/**
 * 木胴縁（一部界壁面）の材積係数 m³/㎡ — 拾い面積(界壁面㎡) → 発注材積(m³)
 *
 * 【XLS原典（2026-07-24・両物件の集計表数式まで辿って確定）】
 *   アルファ 集計表 X86 = 0.0098 … Y85 {=W85*X$86}
 *     W85 = 界壁面の全戸合計45.423㎡（C85 = 'Ａタイプ'!P158+P212+P264+P321 = 5.047㎡/戸）
 *     → Y85 = 45.423 × 0.0098 = 0.4451454 m³ ＝ 集計表AJ列（構造材・軸組み）の1項目
 *     → 戸当 0.4451454 ÷ 9戸 = 0.049461 m³/戸
 *   別府   集計表 X86 = 0.0098 … Y85 = 122.1288 × 0.0098 = 1.19686224（行ラベル「部分界壁 ｔ9.5+木胴縁」）
 *   両物件で同値 → 物件不変の材積係数として扱う（scripts/check-engine-constants.mjs で監視）
 *
 * 【旧実装が誤っていた点（2026-07-24是正）】
 *   旧: DOBUCHI_M_PER_SQM = 1/0.455（横胴縁@455の単方向1層）× 断面45×30 = 0.0029670 m³/㎡
 *   これはXLS実測0.0098の約1/3.3で、**係数が-69.7%低い**。にもかかわらず結果が-46%で済んでいたのは
 *   拾い面積側が過大（下記 rc_furring_sqm=9.77㎡ を投入。正しくは界壁面5.047㎡）だったため。
 *   **係数だけ直すと 9.77×0.0098=0.0957 = +78% に反転する**（相殺誤差。A-2下地高と同じ構造）
 *   → 係数と拾い面積をセットで是正する（scripts/test-dobuchi-volume.mjs が反転を固定）
 *
 * 係数の物理的意味: 0.0098 ÷ 断面0.00135㎡ ≒ 7.26 m/㎡ の材長。単方向@455（2.20m/㎡）では説明できず、
 * 縦横格子@276相当にあたる。標準ピッチに一致しないため**幾何モデルからの再現はしない**。
 * XLSの実測係数（プロの拾い出しの正）をそのまま採用する（間仕切下地0.0116・天井下地0.0081と同じ扱い）。
 */
export const DOBUCHI_M3_PER_SQM = 0.0098;

/**
 * 木胴縁の材積(m³) = 界壁面（一部界壁）の拾い面積(㎡) × DOBUCHI_M3_PER_SQM
 *
 * 引数は「界壁面」の面積のみ。RC面木(D下地)全般（EV廻り・収納内コンパネ面）は**含めない**。
 *
 * 【分離の根拠は「係数が違う」ではなく「集計先の行が違う」（2026-07-24 訂正）】
 *   旧記述は「EV面は別係数(X27)へ入る」としていたが誤り。実セルを検算すると3行とも同係数0.0098:
 *     r26 EV面      : Y26 {=W26*X$27} = 80.955 × 0.0098 = 0.793359   → AJ26
 *     r73 収納内RC面 : Y73 {=W73*X$72} = 67.59  × 0.0098 = 0.662382   → AK73（構造材・天井）
 *     r85 界壁面     : Y85 {=W85*X$86} = 45.423 × 0.0098 = 0.4451454  → AJ85（＝この関数の対象）
 *   違うのは集計先の列・行＝見積明細で別々の発注行になる点であり、
 *   見積明細「木胴縁（一部界壁面）」3.6m³/67戸 に対応するのは r85 の1行のみ。
 *   （「係数が違うから分ける」と読むと、係数を揃えれば合算してよいと誤解される）
 */
export function dobuchiVolumeM3(kaibeFaceSqm) {
  if (!(kaibeFaceSqm > 0)) return 0;
  return Math.round(kaibeFaceSqm * DOBUCHI_M3_PER_SQM * 10000) / 10000;
}
